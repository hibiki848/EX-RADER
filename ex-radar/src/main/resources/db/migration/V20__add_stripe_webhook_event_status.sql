-- Stripe Webhookの「受信済み」と「正常処理済み」を区別できるようにする。
-- 従来はstripe_event_idの存在だけで二重処理を防いでいたため、業務処理が例外で失敗した場合でも
-- イベント行自体は既にINSERT済みのまま残り、Stripeが同じイベントを再送しても「処理済み」と
-- 誤判定して再処理が永久に行われない問題があった。statusを持たせ、PROCESSED以外は
-- 再送時に再処理を許可する(受信済み≠正常処理済み)。
-- 既存行(このマイグレーション以前に記録されたもの)は、当時の実装で例外時も200を返し
-- リトライを止めていたため実質的に「それ以上再送されてこない=処理はそこで終わっている」
-- 状態であり、今更再処理させると別の不整合を招きかねない。安全側に倒し、
-- 既存行は全てPROCESSED(処理済み)として扱う。
ALTER TABLE stripe_webhook_events ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'PROCESSED';
